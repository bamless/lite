local syntax = require "core.syntax"

syntax.add {
  files = { "%.jsr$" },
  headers = "^#!.*[ /]jstar",
  comment = "//",
  patterns = {
    { pattern = "//.-\n",                    type = "comment"  },
    { pattern = "#!.-\n",                    type = "comment"  },
    { pattern = { '"', '"', '\\' },          type = "string"   },
    { pattern = { "'", "'", '\\' },          type = "string"   },
    { pattern = "0x[%da-f]+",                type = "number"   },
    { pattern = "%d*%.?%d+e[%+%-]?%d+",      type = "number"   },
    { pattern = "%d*%.?%d+",                 type = "number"   },
    { pattern = "@[%a_][%w_]*",              type = "function" },
    { pattern = "[%+%-=/%*%^%%<>!~|&#]",     type = "operator" },
    { pattern = "%u[%u%d_]*%f[^%w_]",        type = "literal"  },
    { pattern = "%u[%w_]*",                  type = "keyword2" },
    { pattern = "[%a_][%w_]*%f[(]",          type = "function" },
    { pattern = "[%a_][%w_]*",               type = "symbol"   },
  },
  symbols = {
    ["and"]       = "keyword",
    ["as"]        = "keyword",
    ["begin"]     = "keyword",
    ["break"]     = "keyword",
    ["class"]     = "keyword",
    ["construct"] = "keyword",
    ["continue"]  = "keyword",
    ["elif"]      = "keyword",
    ["else"]      = "keyword",
    ["end"]       = "keyword",
    ["ensure"]    = "keyword",
    ["except"]    = "keyword",
    ["for"]       = "keyword",
    ["fun"]       = "keyword",
    ["if"]        = "keyword",
    ["import"]    = "keyword",
    ["in"]        = "keyword",
    ["is"]        = "keyword",
    ["native"]    = "keyword",
    ["or"]        = "keyword",
    ["raise"]     = "keyword",
    ["return"]    = "keyword",
    ["static"]    = "keyword",
    ["try"]       = "keyword",
    ["var"]       = "keyword",
    ["while"]     = "keyword",
    ["with"]      = "keyword",
    ["yield"]     = "keyword",
    ["super"]     = "keyword2",
    ["this"]      = "keyword2",
    ["true"]      = "literal",
    ["false"]     = "literal",
    ["null"]      = "literal",
  },
}
