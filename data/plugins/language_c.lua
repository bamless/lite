local syntax = require "core.syntax"

syntax.add {
  files = { "%.c$", "%.h$", "%.inl$", "%.cpp$", "%.hpp$" },
  comment = "//",
  patterns = {
    { pattern = "//.-\n",                                      type = "comment" },
    { pattern = { "/%*", "%*/" },                              type = "comment" },
    { pattern = { '"', '"', '\\' },                            type = "string" },
    { pattern = { "'", "'", '\\' },                            type = "string" },
    { pattern = "(#[ \t]*include[ \t]*)(<[^>\r\n]+>)",         type = { "keyword", "string" } },
    { pattern = "(#[ \t]*define[ \t]+)([%a_][%w_]*)%f[^%w_(]", type = { "keyword", "literal" } }, -- Function-like macro
    -- Only these directives take a macro name; #if takes an expression.
    { pattern = "(#[ \t]*ifdef[ \t]+)([%a_][%w_]*)",           type = { "keyword", "literal" } },
    { pattern = "(#[ \t]*ifndef[ \t]+)([%a_][%w_]*)",          type = { "keyword", "literal" } },
    { pattern = "#[ \t]*[%a_]?[%w_]*",                         type = "keyword" },                -- Normal macro
    { pattern = "0[xX]%x[%x']*[uUlL]*",                        type = "number" },
    { pattern = "0[bB][01][01']*[uUlL]*",                      type = "number" },
    { pattern = "%d[%d']*%.?[%d']*[eE][%+%-]?%d[%d']*[fFlL]?", type = "number" },
    { pattern = "%.%d[%d']*[eE][%+%-]?%d[%d']*[fFlL]?",        type = "number" },
    { pattern = "%d[%d']*%.[%d']*[fFlL]?",                     type = "number" },
    { pattern = "%.%d[%d']*[fFlL]?",                           type = "number" },
    { pattern = "%d[%d']*[uUlL]*",                             type = "number" },
    { pattern = "[%+%-=/%*%^%%<>!~|&]",                        type = "operator" },
    { pattern = "(struct)([ \t]+)([%a_][%w_]*)",               type = { "keyword", "normal", "keyword2" } },
    { pattern = "(union)([ \t]+)([%a_][%w_]*)",                type = { "keyword", "normal", "keyword2" } },
    { pattern = "(enum)([ \t]+)([%a_][%w_]*)",                 type = { "keyword", "normal", "keyword2" } },
    { pattern = "([%a_][%w_]*)([ \t]*%()",                     type = { "function", "normal" } },
    { pattern = "[%a_][%w_]*",                                 type = "symbol" },
  },
  symbols = {
    ["if"]             = "keyword",
    ["else"]           = "keyword",
    ["do"]             = "keyword",
    ["while"]          = "keyword",
    ["for"]            = "keyword",
    ["break"]          = "keyword",
    ["continue"]       = "keyword",
    ["return"]         = "keyword",
    ["goto"]           = "keyword",
    ["struct"]         = "keyword",
    ["union"]          = "keyword",
    ["typedef"]        = "keyword",
    ["enum"]           = "keyword",
    ["extern"]         = "keyword",
    ["static"]         = "keyword",
    ["volatile"]       = "keyword",
    ["const"]          = "keyword",
    ["inline"]         = "keyword",
    ["switch"]         = "keyword",
    ["case"]           = "keyword",
    ["default"]        = "keyword",
    ["auto"]           = "keyword",
    ["register"]       = "keyword",
    ["restrict"]       = "keyword",
    ["sizeof"]         = "keyword",
    ["_Alignas"]       = "keyword",
    ["_Alignof"]       = "keyword",
    ["_Atomic"]        = "keyword",
    ["_Generic"]       = "keyword",
    ["_Noreturn"]      = "keyword",
    ["_Static_assert"] = "keyword",
    ["_Thread_local"]  = "keyword",
    ["void"]           = "keyword",
    ["int"]            = "keyword2",
    ["short"]          = "keyword2",
    ["long"]           = "keyword2",
    ["float"]          = "keyword2",
    ["double"]         = "keyword2",
    ["char"]           = "keyword2",
    ["unsigned"]       = "keyword2",
    ["signed"]         = "keyword2",
    ["_Bool"]          = "keyword2",
    ["_Complex"]       = "keyword2",
    ["_Imaginary"]     = "keyword2",
    ["bool"]           = "keyword2",
    ["true"]           = "literal",
    ["false"]          = "literal",
    ["NULL"]           = "literal",
  },
}
